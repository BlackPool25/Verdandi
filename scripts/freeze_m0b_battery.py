#!/usr/bin/env python3
"""Freeze the M0b battery manifest (Phase B1).

Builds the deterministic 182-row machine×class fault matrix from
twin.build_faults_variant + fixed episode-seed assignment, and writes a
hash-pinned JSON artifact. Re-running with the same master seed produces a
byte-identical file (provenance for the no-subsetting rule).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from src import config, twin

MASTER_SEED = 777
GATEWAY_MACHINES = ("ASM0", "ASM1", "INSP0", "ASM2", "RWK0")
N_CLEAN_EPISODES = 10
FAULT_EPISODE_BASE = 30001
CLEAN_EPISODE_BASE = 30201


def build_manifest(master_seed: int = MASTER_SEED) -> dict:
    """Build the frozen battery manifest (pure; no I/O)."""
    rows = twin.build_faults_variant(master_seed, cap_budget=True)
    gw = [r for r in rows if r["origin"] in GATEWAY_MACHINES]
    canonical = json.dumps(rows, sort_keys=True, default=str)
    fault_episodes = list(range(FAULT_EPISODE_BASE, FAULT_EPISODE_BASE + len(rows)))
    clean_episodes = list(
        range(CLEAN_EPISODE_BASE, CLEAN_EPISODE_BASE + N_CLEAN_EPISODES)
    )
    return {
        "manifest": "m0b-battery-v1",
        "master_seed": master_seed,
        "code_version": config.CODE_VERSION,
        "twin_schema": config.TWIN_SCHEMA,
        "cap_budget": True,
        "gateway_machines": list(GATEWAY_MACHINES),
        "gateway_rows": len(gw),
        "gateway_share": len(gw) / len(rows),
        "gateway_quota_waived_to": ">=19%",
        "rows": rows,
        "fault_episodes": fault_episodes,
        "clean_episodes": clean_episodes,
        "episode_seeds": sorted(fault_episodes + clean_episodes),
        "sha256": hashlib.sha256(canonical.encode("utf-8")).hexdigest(),
    }


def render_matrix_markdown(manifest: dict) -> str:
    """Render the frozen fault table for the prereg appendix."""
    lines = [
        f"<!-- GENERATED by scripts/freeze_m0b_battery.py — do not hand-edit. sha256={manifest['sha256']} -->",
        "",
        "| fault id | machine | t0 | dur | mag_sigma | rung | class | episode |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r, ep in zip(manifest["rows"], manifest["fault_episodes"]):
        lines.append(
            f"| {r['id']} | {r['origin']} | {r['t0']} | {r['dur']} | "
            f"{r['mag_sigma']:.3f} | {r['mag_rung']} | {r['class']} | {ep} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """CLI: write manifest JSON + matrix markdown (byte-deterministic)."""
    parser = argparse.ArgumentParser(description="Freeze M0b battery manifest")
    parser.add_argument("--out", default="artifacts/m0b_battery_manifest.json")
    parser.add_argument("--matrix-out", default="docs/M0B_BATTERY_MATRIX.md")
    parser.add_argument("--master-seed", type=int, default=MASTER_SEED)
    args = parser.parse_args(argv)

    manifest = build_manifest(master_seed=args.master_seed)
    out_path = pathlib.Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        json.dumps(manifest, indent=2, sort_keys=True, default=str) + "\n",
        encoding="utf-8",
    )
    matrix_path = pathlib.Path(args.matrix_out)
    matrix_path.parent.mkdir(parents=True, exist_ok=True)
    matrix_path.write_text(render_matrix_markdown(manifest), encoding="utf-8")
    print(f"Froze {len(manifest['rows'])} faults sha={manifest['sha256'][:16]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
